import Foundation

/// Everything the detached installer needs. Paths are absolute because the
/// script runs after Pulse has exited and inherits no working directory.
struct UpdateInstallPlan: Equatable, Sendable {
  let stagedAppPath: String
  let destinationAppPath: String
  let backupAppPath: String
  let logPath: String
  let stagingRootPath: String
  let oldProcessIdentifier: Int32
  let relaunch: Bool
  /// 0.2s per iteration, so the default tolerates four minutes of shutdown.
  var waitIterations: Int = 1200

  init(
    stagedAppPath: String,
    destinationAppPath: String,
    backupAppPath: String,
    logPath: String,
    stagingRootPath: String,
    oldProcessIdentifier: Int32,
    relaunch: Bool,
    waitIterations: Int = 1200
  ) {
    self.stagedAppPath = stagedAppPath
    self.destinationAppPath = destinationAppPath
    self.backupAppPath = backupAppPath
    self.logPath = logPath
    self.stagingRootPath = stagingRootPath
    self.oldProcessIdentifier = oldProcessIdentifier
    self.relaunch = relaunch
    self.waitIterations = waitIterations
  }
}

/// Generates the POSIX shell script that swaps the app bundle after Pulse exits.
///
/// The script is the only code that writes to the installed app, so it is
/// written to be boring: wait for the old pid, back up, copy, verify the
/// signature, restore on any failure, optionally relaunch, and log every branch.
enum UpdateInstallScript {
  static func make(for plan: UpdateInstallPlan) -> String {
    """
    #!/bin/sh
    # Generated by Pulse when installing an update. Safe to delete.
    set -u

    LOG=\(quoted(plan.logPath))
    DESTINATION=\(quoted(plan.destinationAppPath))
    STAGED=\(quoted(plan.stagedAppPath))
    BACKUP=\(quoted(plan.backupAppPath))
    STAGING_ROOT=\(quoted(plan.stagingRootPath))
    OLD_PID=\(plan.oldProcessIdentifier)
    RELAUNCH=\(plan.relaunch ? 1 : 0)
    WAIT_ITERATIONS=\(plan.waitIterations)

    log() {
      printf '%s %s\\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*" >>"$LOG" 2>/dev/null || true
    }

    mkdir -p "$(dirname "$LOG")" 2>/dev/null || true
    log "installer start: pid=$OLD_PID destination=$DESTINATION"

    attempt=0
    while kill -0 "$OLD_PID" 2>/dev/null; do
      attempt=$((attempt + 1))
      if [ "$attempt" -ge "$WAIT_ITERATIONS" ]; then
        log "timed out waiting for the running app to quit; nothing was replaced"
        exit 1
      fi
      sleep 0.2
    done

    mkdir -p "$(dirname "$BACKUP")" 2>/dev/null || true
    rm -rf "$BACKUP"
    if [ -e "$DESTINATION" ]; then
      if ! /usr/bin/ditto "$DESTINATION" "$BACKUP" >>"$LOG" 2>&1; then
        log "backup failed; nothing was replaced"
        exit 1
      fi
    fi

    rm -rf "$DESTINATION"
    if ! /usr/bin/ditto "$STAGED" "$DESTINATION" >>"$LOG" 2>&1; then
      log "copy failed; restoring the previous app"
      rm -rf "$DESTINATION"
      if [ -e "$BACKUP" ]; then /usr/bin/ditto "$BACKUP" "$DESTINATION" >>"$LOG" 2>&1; fi
      exit 1
    fi

    if ! /usr/bin/codesign --verify --deep --strict "$DESTINATION" >>"$LOG" 2>&1; then
      log "signature verification failed; restoring the previous app"
      rm -rf "$DESTINATION"
      if [ -e "$BACKUP" ]; then /usr/bin/ditto "$BACKUP" "$DESTINATION" >>"$LOG" 2>&1; fi
      exit 1
    fi

    rm -rf "$STAGING_ROOT" 2>/dev/null || true
    log "installed successfully"

    if [ "$RELAUNCH" -eq 1 ]; then
      /usr/bin/open "$DESTINATION" >>"$LOG" 2>&1 || log "could not relaunch the updated app"
    fi
    exit 0
    """
  }

  /// Single-quotes a value for `sh`, escaping embedded quotes. Every value that
  /// reaches the script goes through this.
  static func quoted(_ value: String) -> String {
    "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
  }
}

protocol UpdateInstalling: Sendable {
  func install(_ plan: UpdateInstallPlan) throws
}

/// Writes the script and starts it fully detached, so it survives Pulse's exit.
struct DetachedScriptInstaller: UpdateInstalling {
  let scriptDirectory: URL

  func install(_ plan: UpdateInstallPlan) throws {
    let fileManager = FileManager.default
    try fileManager.createDirectory(at: scriptDirectory, withIntermediateDirectories: true)
    let scriptURL = scriptDirectory.appendingPathComponent(
      "install-\(UUID().uuidString).sh")
    guard let data = UpdateInstallScript.make(for: plan).data(using: .utf8) else {
      throw UpdateInstallError.couldNotWriteScript
    }
    try data.write(to: scriptURL, options: [.atomic])
    try fileManager.setAttributes(
      [.posixPermissions: 0o700], ofItemAtPath: scriptURL.path)

    // `nohup ... &` inside a shell that exits immediately reparents the
    // installer to launchd, so quitting Pulse does not take it down.
    let command =
      "/usr/bin/nohup /bin/sh \(UpdateInstallScript.quoted(scriptURL.path)) >/dev/null 2>&1 &"
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/bin/sh")
    process.arguments = ["-c", command]
    do {
      try process.run()
    } catch {
      throw UpdateInstallError.couldNotStartInstaller(error.localizedDescription)
    }
    process.waitUntilExit()
    guard process.terminationStatus == 0 else {
      throw UpdateInstallError.couldNotStartInstaller(
        "/bin/sh exited with \(process.terminationStatus)")
    }
  }
}

enum UpdateInstallError: LocalizedError, Equatable {
  case couldNotWriteScript
  case couldNotStartInstaller(String)

  var errorDescription: String? {
    switch self {
    case .couldNotWriteScript: "Pulse could not write the update installer script."
    case .couldNotStartInstaller(let detail):
      "Pulse could not start the update installer. \(detail)"
    }
  }
}